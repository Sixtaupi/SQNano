-- Differential test schema: every affinity, collations, several indexes.
CREATE TABLE t (
    id INTEGER PRIMARY KEY,
    a INTEGER,
    b REAL,
    c TEXT,
    d,
    e NUMERIC,
    f TEXT COLLATE NOCASE
);
CREATE INDEX t_a ON t(a);
CREATE INDEX t_cf ON t(c, f DESC);
CREATE INDEX t_e ON t(e);

CREATE TABLE u (
    k TEXT PRIMARY KEY,
    v INTEGER NOT NULL DEFAULT 0,
    w REAL CHECK (w IS NULL OR w >= 0)
);

-- Foreign keys (the differential test runs with PRAGMA foreign_keys = ON).
CREATE TABLE p (id INTEGER PRIMARY KEY, name TEXT UNIQUE, grp INTEGER);
CREATE TABLE ch (
    id INTEGER PRIMARY KEY,
    pid INTEGER REFERENCES p(id) ON DELETE CASCADE ON UPDATE CASCADE,
    pname TEXT REFERENCES p(name) ON DELETE SET NULL ON UPDATE CASCADE,
    note TEXT
);
CREATE INDEX ch_pid ON ch(pid);
CREATE TABLE node (id INTEGER PRIMARY KEY, parent INTEGER REFERENCES node(id) ON DELETE CASCADE, v INTEGER);
CREATE TABLE na (id INTEGER PRIMARY KEY, pid INTEGER NOT NULL REFERENCES p(id));
CREATE TABLE rs (id INTEGER PRIMARY KEY, pid INTEGER REFERENCES p ON DELETE RESTRICT ON UPDATE RESTRICT);
CREATE TABLE df (id INTEGER PRIMARY KEY, pid INTEGER, FOREIGN KEY (pid) REFERENCES p(id) DEFERRABLE INITIALLY DEFERRED);
CREATE TABLE sd (id INTEGER PRIMARY KEY, pid INTEGER DEFAULT 1 REFERENCES p(id) ON DELETE SET DEFAULT);

-- WITHOUT ROWID: a composite key (NOCASE, DESC), a secondary index, a UNIQUE column.
CREATE TABLE wr (
    g TEXT COLLATE NOCASE,
    n INTEGER,
    v REAL,
    w TEXT UNIQUE,
    PRIMARY KEY (g, n DESC)
) WITHOUT ROWID;
CREATE INDEX wr_v ON wr(v);
-- A WITHOUT ROWID parent and child; the child key leads the child's PRIMARY KEY.
CREATE TABLE wp (code TEXT PRIMARY KEY, label TEXT) WITHOUT ROWID;
CREATE TABLE wc (
    code TEXT REFERENCES wp(code) ON DELETE CASCADE ON UPDATE CASCADE,
    seq INTEGER,
    x INTEGER,
    PRIMARY KEY (code, seq)
) WITHOUT ROWID;
CREATE INDEX wc_x ON wc(x DESC);
